"""
sensors.py
==========
Simulated environmental sensor module for the Smart Irrigation Autonomous Agent.

Simulates readings for:
- Soil moisture (0% - 100%)
- Temperature (-10°C - 60°C)
- Humidity (0% - 100%)
- Rainfall probability (0% - 100%)

NOTE: All readings generated by this module are SIMULATED and intended solely
for coursework, testing, and local demonstration. No physical hardware or
real weather services are connected.
"""

from __future__ import annotations

import math
import random
import time
from dataclasses import asdict, dataclass
from typing import Any, Dict, Optional, Tuple


@dataclass
class SensorReading:
    """Represents a snapshot of environmental sensor readings."""

    soil_moisture: float  # Percentage: 0.0 to 100.0%
    temperature: float  # Degrees Celsius: -10.0°C to 60.0°C
    humidity: float  # Percentage: 0.0 to 100.0%
    rainfall_probability: float  # Percentage: 0.0 to 100.0%
    timestamp: float = 0.0  # Unix timestamp
    source: str = "simulated"  # 'simulated' or 'manual'

    def __post_init__(self) -> None:
        if self.timestamp == 0.0:
            self.timestamp = time.time()

    def to_dict(self) -> Dict[str, Any]:
        """Convert reading to a standard dictionary."""
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> SensorReading:
        """Create a SensorReading instance from a dictionary."""
        return cls(
            soil_moisture=float(data["soil_moisture"]),
            temperature=float(data["temperature"]),
            humidity=float(data["humidity"]),
            rainfall_probability=float(data["rainfall_probability"]),
            timestamp=float(data.get("timestamp", time.time())),
            source=str(data.get("source", "manual")),
        )


def validate_sensor_data(
    soil_moisture: Any,
    temperature: Any,
    humidity: Any,
    rainfall_probability: Any,
) -> Tuple[bool, str]:
    """
    Validate that all sensor input values are numeric and within supported ranges.

    Supported ranges:
    - soil_moisture: 0.0% to 100.0%
    - temperature: -10.0°C to 60.0°C
    - humidity: 0.0% to 100.0%
    - rainfall_probability: 0.0% to 100.0%

    Returns:
        (is_valid, error_message): A boolean indicating validity and an error string if invalid.
    """
    fields = [
        ("soil_moisture", soil_moisture, 0.0, 100.0, "Soil moisture", "%"),
        ("temperature", temperature, -10.0, 60.0, "Temperature", "°C"),
        ("humidity", humidity, 0.0, 100.0, "Humidity", "%"),
        ("rainfall_probability", rainfall_probability, 0.0, 100.0, "Rainfall probability", "%"),
    ]

    for name, value, min_val, max_val, label, unit in fields:
        if value is None:
            return False, f"Missing required sensor field: '{name}' cannot be None."

        # Reject booleans (as bool is a subclass of int in Python)
        if isinstance(value, bool):
            return False, f"Invalid value for {label}: boolean values are not accepted."

        # Must be int or float
        if not isinstance(value, (int, float)):
            try:
                value = float(value)
            except (ValueError, TypeError):
                return False, f"Invalid value for {label}: must be a numeric value, received '{value}'."

        # Check for NaN / Inf
        if math.isnan(value) or math.isinf(value):
            return False, f"Invalid value for {label}: finite number required, received '{value}'."

        # Check bounds
        if value < min_val or value > max_val:
            return (
                False,
                f"{label} ({value}{unit}) is outside valid range [{min_val}{unit}, {max_val}{unit}].",
            )

    return True, ""


def generate_sensor_reading(
    previous: Optional[SensorReading] = None,
    is_irrigating: bool = False,
    source: str = "simulated",
) -> SensorReading:
    """
    Generate realistic simulated environmental readings.

    If a previous reading is provided, values evolve smoothly:
    - If irrigating is active: soil moisture increases steadily.
    - If not irrigating: soil moisture gently dries out based on temperature.
    - Temperature, humidity, and rainfall probability undergo natural random walk variations.

    All generated values are strictly clamped to their valid ranges.
    """
    if previous is None:
        # Default representative baseline
        soil_moisture = 26.0
        temperature = 34.0
        humidity = 45.0
        rainfall_probability = 15.0
    else:
        # Simulate physical evolution
        if is_irrigating:
            # Irrigation increases moisture by 4% to 8% per cycle
            soil_moisture = previous.soil_moisture + random.uniform(4.0, 8.0)
        else:
            # Evaporation/drying: faster drying if hotter
            dry_rate = 0.5 + (max(0.0, previous.temperature - 20.0) * 0.08)
            soil_moisture = previous.soil_moisture - random.uniform(dry_rate * 0.5, dry_rate * 1.5)

        # Temperature fluctuates smoothly (+/- 1.5°C)
        temp_delta = random.uniform(-1.5, 1.5)
        temperature = previous.temperature + temp_delta

        # Humidity fluctuates inversely with temperature (+/- 3%)
        hum_delta = -0.5 * temp_delta + random.uniform(-2.0, 2.0)
        humidity = previous.humidity + hum_delta

        # Rainfall probability shifts gradually (+/- 5%)
        rain_delta = random.uniform(-5.0, 5.0)
        rainfall_probability = previous.rainfall_probability + rain_delta

    # Strictly clamp all values to physical ranges
    soil_moisture = max(0.0, min(100.0, round(soil_moisture, 1)))
    temperature = max(-10.0, min(60.0, round(temperature, 1)))
    humidity = max(0.0, min(100.0, round(humidity, 1)))
    rainfall_probability = max(0.0, min(100.0, round(rainfall_probability, 1)))

    return SensorReading(
        soil_moisture=soil_moisture,
        temperature=temperature,
        humidity=humidity,
        rainfall_probability=rainfall_probability,
        timestamp=time.time(),
        source=source,
    )
